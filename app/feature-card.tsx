export default function FeatureCard({ feature }: { feature: Feature }) {
  const textId = useId();
  const [expanded, setExpanded] = useState(false);
  const needsToggle = feature.description.length > FEATURE_PREVIEW_CHAR_THRESHOLD;

  return (
    <article className="bg-surface-2 p-6 rounded-lg shadow-brand hover:shadow-brand-lg transition-shadow border border-border flex flex-col">
      <div className="w-12 h-12 bg-brand rounded-lg flex items-center justify-center mb-4">
        <svg
          className="w-6 h-6 text-brand-text"
          fill="none"
          stroke="currentColor"
          viewBox="0 0 24 24"
          aria-hidden="true"
        >
          {ICONS[feature.id]}
        </svg>
      </div>
      <h3 className="text-xl font-semibold text-foreground mb-2">{feature.title}</h3>
      <p
        id={textId}
        className={`text-foreground-2 text-sm leading-relaxed${
          needsToggle && !expanded ? " line-clamp-4" : ""
        }`}
      >
        {feature.description}
      </p>
      {needsToggle ? (
        <button
          type="button"
          className="mt-3 self-start text-sm font-semibold text-brand hover:text-brand-strong transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand/40 rounded"
          aria-expanded={expanded}
          aria-controls={textId}
          onClick={() => setExpanded((value) => !value)}
        >
          {expanded ? "Zobraziť menej" : "Zobraziť viac"}
        </button>
      ) : null}
    </article>
  );
}
